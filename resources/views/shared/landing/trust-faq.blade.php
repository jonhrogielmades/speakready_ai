      <div class="faq-list reveal">
         <details open>
            <summary>What can I customize before starting?</summary>
            <p>Choose your target position, difficulty, question count, timer, question types, response mode, coaching mode, and Camera Detection setting.</p>
         </details>
         <details>
            <summary>What is the difference between Coaching On and Real Interview Mode?</summary>
            <p>Coaching On gives guidance while you practice. Real Interview Mode keeps the session quieter so you can complete the run more independently before reviewing your score and feedback.</p>
         </details>
         <details>
            <summary>Do I need to turn on my camera?</summary>
            <p>No. Camera Detection is optional. You can leave it off and continue with an answer-focused text, voice, or hybrid practice session.</p>
         </details>
         <details>
            <summary>Does Camera Detection decide my readiness score?</summary>
            <p>No. Camera-related observations support coaching notes. Readiness scoring stays focused on answer quality and does not infer confidence, honesty, or personality.</p>
         </details>
         <details>
            <summary>How are my interview records protected?</summary>
            <p>Interview records require account access, submitted data is validated, and the application checks that the signed-in user owns the session being opened.</p>
         </details>
         <details>
            <summary>What can I review after a session?</summary>
            <p>Depending on the session, you can review scores, answer evidence, coaching notes, recommended learning activities, readiness trends, reports, and session history.</p>
         </details>
